# Derived from the catalog so adding a language means adding its labels and
# nothing else.
SUPPORTED_LANGUAGES: Tuple[str, ...] = tuple(LABELS)


def normalize_language(value: Any) -> str:
    """Maps any UI/locale value onto a language this renderer supports."""
    code = str(value or "").strip().lower().replace("_", "-").split("-")[0]
    return code if code in LABELS else DEFAULT_LANGUAGE


def is_rtl(language: Any) -> bool:
    return normalize_language(language) in RTL_LANGUAGES


def contains_rtl(text: Any) -> bool:
    return bool(_RTL_CHARS.search(str(text or "")))


# ---------------------------------------------------------------------------
# Fonts
# ---------------------------------------------------------------------------
_font_lock = threading.Lock()
_arabic_fonts_ready: Optional[bool] = None


def register_rtl_fonts() -> bool:
    """Registers the bundled Arabic family once per process.

    Returns ``False`` (and logs) when the font files are missing so callers can
    degrade to Helvetica instead of failing the download outright.
    """
    global _arabic_fonts_ready

    with _font_lock:
        if _arabic_fonts_ready is not None:
            return _arabic_fonts_ready

        try:
            from reportlab.pdfbase import pdfmetrics
            from reportlab.pdfbase.ttfonts import TTFont

            for font_name, filename in ARABIC_FONT_FILES:
                path = FONT_DIR / filename
                if not path.is_file():
                    raise FileNotFoundError(path)
                pdfmetrics.registerFont(TTFont(font_name, str(path)))

            pdfmetrics.registerFontFamily(
                "MizaanArabic",
                normal="MizaanArabic",
                bold="MizaanArabic-Bold",
                # The family has no italic; reusing the upright faces keeps
                # <i> markup renderable instead of raising.
                italic="MizaanArabic",
                boldItalic="MizaanArabic-Bold",
            )
            _arabic_fonts_ready = True
        except Exception:
            logger.exception(
                "Arabic font registration failed - falling back to Helvetica, "
                "which cannot render Arabic glyphs."
            )
            _arabic_fonts_ready = False

        return _arabic_fonts_ready


# ---------------------------------------------------------------------------
# Shaping / bidi
# ---------------------------------------------------------------------------
_shaper_lock = threading.Lock()
_shaper: Optional[Tuple[Any, Any]] = None
_shaper_loaded = False


def _load_shaper() -> Optional[Tuple[Any, Any]]:
    global _shaper, _shaper_loaded

    with _shaper_lock:
        if _shaper_loaded:
            return _shaper
        _shaper_loaded = True
        try:
            import arabic_reshaper
            from bidi.algorithm import get_display

            _shaper = (arabic_reshaper.reshape, get_display)
        except Exception:
            logger.exception(
                "arabic-reshaper/python-bidi unavailable - Arabic will render "
                "unshaped and in logical order."
            )
            _shaper = None
        return _shaper


def shape_rtl(text: Any) -> str:
    """Returns one line of RTL text in display order.

    Must be applied per line: the bidirectional algorithm is defined on a
    single line of text, so shaping a whole paragraph and wrapping afterwards
    reverses the reading order of every line but the first.
    """
    value = "" if text is None else str(text)
    if not value or not contains_rtl(value):
        return value

    shaper = _load_shaper()
    if shaper is None:
        return value

    reshape, get_display = shaper
    try:
        return get_display(reshape(value), base_dir="R")
    except Exception:
        logger.exception("Failed to shape RTL text")
        return value


def wrap_rtl_lines(
    text: Any, font_name: str, font_size: float, max_width: float
) -> List[str]:
    """Greedy word wrap in logical order, returning shaped display lines."""
    value = "" if text is None else str(text)
    if not value.strip():
        return []

    limit = max(float(max_width), 1.0)
    lines: List[str] = []

    for block in value.splitlines():
        words = block.split()
        if not words:
            lines.append("")
            continue

        current = ""
        for word in words:
            candidate = word if not current else f"{current} {word}"
            width = stringWidth(shape_rtl(candidate), font_name, font_size)
            if width <= limit or not current:
                current = candidate
            else:
                lines.append(current)
                current = word
        if current:
            lines.append(current)

    return [shape_rtl(line) for line in lines]


def escape_xml(value: Any) -> str:
    """Report text is model-generated, so markup characters are neutralised."""
    text = "" if value is None else str(value)
    return (
        text.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .strip()
    )


class RtlParagraph(Paragraph):
    """A paragraph that wraps logically and renders in visual order.

    ReportLab wraps text itself, which is incompatible with reordering the
    bidirectional text up front. This flowable therefore performs its own line
    breaking at the width it is handed, shapes each line, and hands ReportLab
    pre-broken lines that need no further reflow.
    """

    def __init__(self, text: Any, style: ParagraphStyle):
        self._logical_text = "" if text is None else str(text).strip()
        self._rtl_style = style
        self._built_width: Optional[float] = None
        super().__init__(escape_xml(self._logical_text) or "&nbsp;", style)

    def _rebuild(self, available_width: float) -> None:
        lines = wrap_rtl_lines(
            self._logical_text,
            self._rtl_style.fontName,
            self._rtl_style.fontSize,
            available_width,
        )
        markup = "<br/>".join(escape_xml(line) for line in lines) or "&nbsp;"
        Paragraph.__init__(self, markup, self._rtl_style)
        self._built_width = available_width

    def wrap(self, availWidth, availHeight):  # noqa: N803 - ReportLab API
        if self._built_width is None or abs(availWidth - self._built_width) > 0.5:
            self._rebuild(availWidth)
        return Paragraph.wrap(self, availWidth, availHeight)


# ---------------------------------------------------------------------------
# Localizer
# ---------------------------------------------------------------------------
class Localizer:
    """Every language-dependent decision the renderer needs, in one object."""

    def __init__(self, language: Any = DEFAULT_LANGUAGE):
        self.language = normalize_language(language)
        self.is_rtl = self.language in RTL_LANGUAGES

        if self.is_rtl and register_rtl_fonts():
            self.font = "MizaanArabic"
            self.font_bold = "MizaanArabic-Bold"
            self.font_italic = "MizaanArabic"
        else:
            self.font, self.font_bold, self.font_italic = LATIN_FONTS

        self.alignment = TA_RIGHT if self.is_rtl else TA_LEFT

    # -- text lookup --------------------------------------------------------
    def text(self, key: str, **params: Any) -> str:
        catalog = LABELS.get(self.language, LABELS[DEFAULT_LANGUAGE])
        template = catalog.get(key) or LABELS[DEFAULT_LANGUAGE].get(key, "")
        if params:
            try:
                return template.format(**params)
            except (KeyError, IndexError):
                return template
        return template

    def _lookup(self, table: Dict[str, Dict[str, str]], key: Any,
                default: str = "") -> str:
        entry = str(key or "").strip()
        catalog = table.get(self.language, table[DEFAULT_LANGUAGE])
        return catalog.get(entry) or table[DEFAULT_LANGUAGE].get(entry, default or entry)

    def section_icon(self, key: str) -> str:
        icons = SECTION_ICONS.get(self.language, SECTION_ICONS[DEFAULT_LANGUAGE])
        return icons.get(key, SECTION_ICONS[DEFAULT_LANGUAGE].get(key, ""))

    def risk_band(self, key: Any) -> str:
        return self._lookup(RISK_BAND_LABELS, key)

    def status(self, key: Any) -> str:
        return self._lookup(STATUS_LABELS, key, self.text("empty_verdict"))

    def priority(self, key: Any) -> str:
        return self._lookup(PRIORITY_LABELS, key)

    def risk_level(self, key: Any) -> str:
        return self._lookup(RISK_LEVEL_LABELS, key)

    def classification(self, value: Any) -> str:
        """Translates the derived English labels, passes model text through."""
        return self._lookup(CLASSIFICATION_LABELS, value, str(value or ""))

    def audit_type(self, value: Any) -> str:
        return self._lookup(AUDIT_TYPE_LABELS, value, str(value or ""))

    def confidentiality_notice(self, configured: Optional[str] = None) -> str:
        # The English notice stays operator-configurable; translations are
        # only used when the operator has not overridden it.
        if self.language == DEFAULT_LANGUAGE and configured:
            return configured
        return self.text("confidentiality_notice")

    def format_date(self, moment: datetime) -> str:
        months = MONTHS.get(self.language, MONTHS[DEFAULT_LANGUAGE])
        return f"{moment.day:02d} {months[moment.month - 1]} {moment.year}"

    # -- rendering helpers --------------------------------------------------
    def shape(self, text: Any) -> str:
        """Prepares a single line for direct canvas drawing."""
        value = "" if text is None else str(text)
        return shape_rtl(value) if self.is_rtl else value

    def paragraph(self, text: Any, style: ParagraphStyle) -> Paragraph:
        if self.is_rtl:
            return RtlParagraph(text, style)
        return Paragraph(escape_xml(text), style)


_ENGLISH = Localizer(DEFAULT_LANGUAGE)
_current: ContextVar[Localizer] = ContextVar("mizaan_report_localizer")


def current_localizer() -> Localizer:
    """The localizer for the report being rendered on this thread/task."""
    return _current.get(_ENGLISH)


def use_language(language: Any) -> Tuple[Localizer, Any]:
    """Activates a language for the current context.

    Returns the localizer and the token needed to restore the previous value,
    so concurrent renders in different languages cannot leak into each other.
    """
    localizer = Localizer(language)
    return localizer, _current.set(localizer)


def reset_language(token: Any) -> None:
    try:
        _current.reset(token)
    except (ValueError, LookupError):  # pragma: no cover - defensive
        pass
