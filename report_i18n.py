"""Localization for rendered audit reports.

The audit language chosen in the UI controls the *whole* report, not just the
sentences written by the model. Everything the renderer adds itself — section
titles, card labels, badges, risk bands, empty-state sentences, the cover sheet
and the page furniture — is looked up here so a report reads as one document in
one language.

Right-to-left support
---------------------
ReportLab draws glyphs in the order it is given them and performs no Unicode
bidirectional reordering or Arabic glyph shaping. Arabic therefore needs three
things that Latin scripts do not:

1. a font that actually contains Arabic glyphs (the built-in Helvetica does
   not, which is why unshaped Arabic previously rendered as empty boxes);
2. contextual shaping, so letters take their initial/medial/final forms;
3. bidirectional reordering, applied *per rendered line* — reordering a whole
   paragraph and then letting ReportLab wrap it would scramble the line order.

:class:`RtlParagraph` satisfies (3) by wrapping the text itself in logical
order at the width it is given, then shaping each resulting line for display.

Both Arabic dependencies are optional at runtime: if they are unavailable the
text still renders with the correct font and content, only unshaped, rather
than failing the whole download.
"""

